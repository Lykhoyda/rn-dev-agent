import assert from 'node:assert/strict';
import test from 'node:test';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../../..');
// packages/claude-plugin is the one directory both marketplaces install; the
// Codex surface lives in its codex-* subtrees. packages/codex-plugin is authoring only.
const distribution = join(root, 'packages/claude-plugin');
const authoring = join(root, 'packages/codex-plugin');
const sourceMap = JSON.parse(
  readFileSync(join(root, 'packages/shared-agent-knowledge/source-map.json'), 'utf8'),
) as {
  hostAdaptations: {
    codex: { adaptedDomainSkills: string[]; adaptedCommands: string[]; commandSkills: string[] };
  };
};
const contract = sourceMap.hostAdaptations.codex;

function directories(path: string): string[] {
  return readdirSync(path, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

test('GH-575 generated Codex skill inventory is exactly 28 with migration disabled', () => {
  assert.equal(contract.adaptedDomainSkills.length, 11);
  assert.equal(contract.adaptedCommands.length, 17);
  assert.deepEqual(contract.commandSkills, contract.adaptedCommands);
  const expected = [...contract.adaptedDomainSkills, ...contract.commandSkills].sort();
  assert.equal(new Set(expected).size, 28);
  assert.deepEqual(directories(join(distribution, 'codex-skills')), expected);
  assert.deepEqual(
    directories(join(authoring, 'skills')),
    [...contract.adaptedDomainSkills].sort(),
  );
  for (const manifestPath of [
    join(distribution, '.codex-plugin/plugin.json'),
    join(authoring, '.codex-plugin/plugin.json'),
  ]) {
    const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
      skills?: unknown;
      commands?: unknown;
      mcpServers?: unknown;
      hooks?: unknown;
    };
    assert.equal(manifest.skills, './codex-skills/');
    assert.deepEqual(manifest.commands, []);
    assert.equal(manifest.mcpServers, './codex.mcp.json');
    assert.deepEqual(
      manifest.hooks,
      { hooks: {} },
      'inline empty hooks keep Claude hooks/ out of Codex',
    );
  }
  assert.equal(existsSync(join(distribution, '.codex-plugin/migrated-command-skills')), false);
  assert.equal(
    existsSync(join(distribution, '.mcp.json')),
    false,
    'Claude must not auto-discover the Codex bootstrap',
  );
});

test('GH-575 every command adapter is generated, explicit-only, and package-relative', () => {
  for (const name of contract.commandSkills) {
    const skill = readFileSync(join(distribution, 'codex-skills', name, 'SKILL.md'), 'utf8');
    const metadata = readFileSync(
      join(distribution, 'codex-skills', name, 'agents/openai.yaml'),
      'utf8',
    );
    assert.equal(skill.startsWith('---\n'), true, `${name} must start with YAML frontmatter`);
    assert.match(skill, /GENERATED by scripts\/build-host-runtimes\.ts/);
    assert.match(skill, new RegExp(`name: ${name}(?:\\n|$)`));
    assert.match(skill, new RegExp(`\\$rn-dev-agent:${name}`));
    assert.match(skill, new RegExp(`\\.\\./\\.\\./codex-commands/${name}\\.md`));
    assert.equal(existsSync(join(distribution, 'codex-commands', `${name}.md`)), true, name);
    assert.match(skill, /conceptual \*\*request\*\*/);
    assert.match(metadata, /allow_implicit_invocation:\s*false/);
    assert.match(metadata, new RegExp(`\\$rn-dev-agent:${name}`));
  }
});

